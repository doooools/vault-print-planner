"""Write tools/placements/COVERAGE.md: for every unit the planner can build, is each of its files placed?

  python coverage.py <_units.json> <stl-placements.json> <_checks.json> <recipes_dir> <out.md> [hardware_report.json]

_units.json  : from coverage.js (the planner's own unit list and files)
unplaced_reasons.json (next to this script): why some files are left out (path regex -> reason).
_checks.json : what was looked at, per unit key or family prefix ("drawer|S|" covers every S drawer):
               {"drawer|S|": {"status": "verified", "render": "...", "note": "..."}, ...}
               The longest matching prefix wins.
recipes_dir  : the recipes' "notes" (orientation fallbacks, latch counts) are copied into the report.
hardware_report.json (from hardware.py): adds the "Hardware" section, the bolts placed per family and why the
rest of the planner's hardware isn't.
layout_checks.json (from check_layouts.py, optional 8th argument; the 7th may be "-"): adds the "Several drawers
in one module" section's motion check.
A unit is "missing" when it has no placement, "doubtful" when its check or its recipe says so, or when
one of its files is neither placed nor explained, and "verified" otherwise.
"""
import collections, json, os, re, sys
sys.stdout.reconfigure(encoding="utf-8")

units_path, pl_path, checks_path, recipes_dir, out = sys.argv[1:6]
HW_REPORT = json.load(open(sys.argv[6], encoding="utf-8")) if len(sys.argv) > 6 and sys.argv[6] != "-" else None
LAY_CHECKS = json.load(open(sys.argv[7], encoding="utf-8")) if len(sys.argv) > 7 else None
UNITS = json.load(open(units_path, encoding="utf-8"))
PL = json.load(open(pl_path, encoding="utf-8"))["units"]
CHECKS = json.load(open(checks_path, encoding="utf-8")) if os.path.exists(checks_path) else {}
NOTES = {}
for f in os.listdir(recipes_dir):
    if f.endswith("_assembly.json"):
        r = json.load(open(os.path.join(recipes_dir, f), encoding="utf-8"))
        if r.get("key") and not r.get("layout"):   # (layouts have their own section)
            NOTES.setdefault(r["key"], []).extend(n for n in r.get("notes", []) if not re.match(r"^\d+ latch", n))

# Files that are not placed on purpose
REASONS = [
    (lambda l, p: l["aid"], "print aid, not part of the finished unit"),
    (lambda l, p: l["alt"] == "whole", "split version of a part: the 3D view draws the one-piece version"),
    (lambda l, p: re.search(r"Grid Dividers/", p), "grid dividers: how many and where is the user's choice"),
    (lambda l, p: re.search(r"SUSTAINERS/05. Universal/Dividers/", p), "case dividers: how many and where is the user's choice"),
]
EXTRA = {k: v for k, v in json.load(open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "unplaced_reasons.json"),
                                          encoding="utf-8")).items() if not k.startswith("_")}


def norm(p):
    return p.lower().replace("'", "").replace("’", "").replace(" ", "")


def check_for(key):
    best = None
    for k, v in CHECKS.items():
        if key.startswith(k) and (best is None or len(k) > len(best[0])):
            best = (k, v)
    return best[1] if best else {}


rows, fam_stats = [], collections.defaultdict(collections.Counter)
for key in sorted(UNITS, key=lambda k: (k.split("|")[0], k)):
    u = UNITS[key]
    pl = PL.get(key)
    placed = {norm(p[0]) for p in pl["parts"]} if pl else set()
    unplaced, explained = [], []
    for path, l in u["lines"].items():
        if norm(path) in placed:
            continue
        why = next((w for test, w in REASONS if test(l, path)), None)
        why = why and ("by design", why)
        why = why or next((("option, not measured", v["why"]) if v["kind"] == "option" else ("by design", v["why"])
                           for pat, v in EXTRA.items() if re.search(pat, path)), None)
        (explained if why else unplaced).append((l["label"], path, why))
    ck = check_for(key)
    notes = NOTES.get(key, [])
    if not pl:
        status = "missing"
    elif ck.get("status") == "doubtful" or any("DOUBTFUL" in n for n in notes) or unplaced:
        status = "doubtful"
    elif ck.get("status") == "verified":
        status = "verified"
    else:
        status = "doubtful"
    fam = "|".join(key.split("|")[:2])
    fam_stats[fam][status] += 1
    rows.append((key, status, pl, unplaced, explained, ck, notes))

L = ["# Placement coverage", "",
     "Generated by `coverage.py` from the planner's own unit list (`coverage.js` runs `src/rules.js` on the",
     "download's file list) and `src/stl-placements.json`. Renders and `.blend` files are outside the repo, in",
     "`VAULT_ASSEMBLY/<family>/` next to the decimated copy (they hold USSA geometry).", "",
     "Status: **verified** = the unit's parts are placed, every other file is explained below, and the family",
     "was checked (renders, sections, a stacked tower from the original files); **doubtful** = placed, but",
     "something is a guess (see the unit's notes);",
     "**missing** = no placement yet.", "", "## By family", "", "| Family | verified | doubtful | missing |", "|---|---|---|---|"]
for fam in sorted(fam_stats):
    c = fam_stats[fam]
    L.append(f"| `{fam}` | {c['verified']} | {c['doubtful']} | {c['missing']} |")
tot = collections.Counter(r[1] for r in rows)
L += ["", f"Total: {len(rows)} units, {tot['verified']} verified, {tot['doubtful']} doubtful, {tot['missing']} missing.", ""]
# Reasons shared by many units, listed once
shared = collections.Counter((lab, why) for r in rows for (lab, _, why) in r[4])
L += ["## Files not placed, and why", "",
      "Listed once here rather than under every unit. *by design*: never placed (print aids, the user's own",
      "divider layout, the split version of a part drawn whole). *option, not measured*: an optional or small",
      "part whose place was not measured in this pass; the units that list it can still be verified.", "",
      "| File (label) | Units | Kind | Why |", "|---|---|---|---|"]
for (lab, (kind, why)), n in sorted(shared.items(), key=lambda x: (x[0][1][0], -x[1])):
    L.append(f"| {lab} | {n} | {kind} | {why} |")

# Hardware: the bolts hardware.py placed, per family and height, against the planner's list and the manual
if HW_REPORT:
    WHY = {"front": "M4 x 14 button, drawer front to box", "case_front": "M4 x 20 button, case front to body",
           "hinge": "M4 x 10 button, hinge leaves to body", "hinge_top": "M4 x 14 button, hinge tops to lid",
           "lock": "M4 x 14 button, lock holders to front", "top_handle": "M6 x 50 countersunk, top handle to grid roof"}
    by = collections.defaultdict(collections.Counter)
    room = collections.defaultdict(list)
    for b in HW_REPORT["bolts"]:
        room[b["rule"]].append(b["room"])
    for k, c in HW_REPORT["counts"].items():
        t, w, d, h = k.split("|")
        if "#" in h:
            continue   # layouts: their own section
        by[(t, w, h)][tuple(sorted((r, n) for r, n in c.items()))] += 1
    L += ["## Hardware (bolts)", "",
          "`hardware.py` finds, on every assembled unit, the holes each kind of bolt goes in and writes `hardware` into",
          "the placements; the page draws the bolts from their standard sizes (no USSA geometry). Counts per unit, the",
          "same on every depth of a family (one row per family and height):", "",
          "| Unit | Bolts placed per unit |", "|---|---|"]
    for (t, w, h), cs in sorted(by.items()):
        for combo, n in cs.items():
            L.append(f"| `{t}|{w}|*|{h}` ({n}) | " + ", ".join(f"{q} x {WHY[r]}" for r, q in combo if q) + " |")
    L += ["", "Room left at the tip (from the bolt's end to the bottom of the hole it goes in, on the axis), all units:", "",
          "| Bolt | Bolts | Room, mm (min / max) |", "|---|---|---|"]
    for r, v in room.items():
        v = [x for x in v if x is not None]
        L.append(f"| {WHY[r]} | {len(v)} | {min(v):.2f} / {max(v):.2f} |")
    L += ["",
          "Every bolt's head bears on its part (the counterbore's floor, the part's face, or the countersink for the M6),",
          "its shank goes down a hole into the next part, and no tip goes past the bottom of its hole (the hinge M4 x 10",
          "and the lock M4 x 14 are exactly as long as their holes are deep). `hw_check.py` cut S, M, L, L2, XL, XL2",
          "drawers, S, M, L, XL cases and S, L, XL grid roofs through their bolts and found no head inside a part.", "",
          "Planner, manual and files (counts per unit; the planner's counts were left as they are):", "",
          "| Bolt | Planner (`rules.js`) | Manual | Holes in the files |", "|---|---|---|---|",
          "| M4 x 14, drawer front | S 2/4, M and L 4/6, XL 4 (1F / 2F-4F), L2 and XL2 the sum of their drawers | x4 for 1F, x6 for 2F/4F (p. 18, drawn on an M) | same as the planner |",
          "| M4 x 20, case front | 7 on every case | x7 per module (p. 17, drawn on an L 4F) | S and M: 4 (1F, 2F), 6 (4F); L: 5 (1F, 2F), 7 (4F); XL: 5. Only the L 4F has 7 |",
          "| M4 x 14, case hinge tops and locks | 16 on every case | x16 per module (p. 17, an L: 2 tops, 2 locks) | L and XL 16; S and M 8 (one hinge top with 4 holes, one lock) |",
          "| M4 x 10, case hinges | 8 | x8 | 8 |",
          "| M6 x 50 countersunk, grid roof top handle | 2 (option) | x2 (p. 18) | 2 |", "",
          "Not placed, and why:", "",
          "| Hardware (planner) | Why |", "|---|---|",
          "| Base, wheels and feet: M16 rod, M4 x 25, 6205ZZ bearings, SCSAW collars, M6 x 90, casters | the printed parts are placed (`stack|...` units); these bought parts are not drawn yet (their places are in README \"Stacks\") |",
          "| Stationary and pull-out handles: M4 x 60, M6 x 30, M6 x 35 hex, M6 heat inserts, M16 rods | same: tower parts, not placed yet |",
          "| Pegboard M4 x 40, backbone M4 x 60-100 | the mounts on the back of a unit are not placed yet |",
          "| Lock pins, hinge rods | printed parts, not bought hardware (the rods are placed with the hinges) |", "",
          "Moving parts: a bolt carries the index of the part that holds it (`part`), and its group is that part's. The",
          "hinge tops' bolts turn with the lid (group `lid`). The case locks' bolts are in the holder, which doesn't move;",
          "if an animation moves a part on its own (a key, a latch, a lock lever), its bolts should get the same motion",
          "through `part`. No bolt is in a moving lock part today.", ""]
# Several drawers in one 2F/4F module (README "Layouts")
lays = collections.defaultdict(lambda: collections.defaultdict(list))
for key, u in PL.items():
    for lid, lay in (u.get("layouts") or {}).items():
        t, w, d, h = key.split("|")
        lays[(w, h)][lid].append((d, len(lay["parts"]), len(lay.get("hardware", [])), len(lay["drawers"])))
if lays:
    L += ["## Several drawers in one module", "",
          "`layouts` of the 2F and 4F drawers (README \"Layouts\"): the drawers' parts at their levels, 48 mm apart as",
          "`measure_levels.py` measured on every 2F/4F shell. Per family, height and layout: the depths placed, the parts",
          "(all drawers, every variant) and the drawer-front bolts per unit.", "",
          "| Unit | Layout | Depths | Drawers | Parts | Bolts |", "|---|---|---|---|---|---|"]
    for (w, h), by_lay in sorted(lays.items()):
        for lid, rows_ in sorted(by_lay.items()):
            ds = ",".join(sorted(r[0] for r in rows_))
            ps = sorted(set(r[1] for r in rows_))
            bs = sorted(set(r[2] for r in rows_))
            L.append(f"| `drawer|{w}|*|{h}` | `{lid}` | {ds} | {rows_[0][3]} | {'/'.join(map(str, ps))} | {'/'.join(map(str, bs))} |")
    if LAY_CHECKS:
        tag = lambda n: (re.search(r"<(\w+)>", n) or [None, None])[1]
        between = [(k, r) for k, v in LAY_CHECKS.items() for r in v
                   if tag(r["pair"][0]) and tag(r["pair"][1]) and tag(r["pair"][0]) != tag(r["pair"][1])]
        kinds = collections.defaultdict(list)
        plain = lambda n: re.sub(r"\s*(\[.*?\]|<.*?>)", "", n)
        for k, v in LAY_CHECKS.items():
            for r in v:
                if r["new"]:
                    a, b = (re.sub(r"^\S+ (Module \d[Ff])", r"\1", plain(x)) for x in r["pair"])
                    kinds[(a, b)].append(r)
        units_ = sorted(set(k.split("#")[0] for k in LAY_CHECKS))
        L += ["", f"Motion check (`check_layouts.py`, each drawer unlocked and pulled out with the others shut and locked in "
              f"place, 21 steps): {len(LAY_CHECKS)} drawers of " + ", ".join(f"`{u}`" for u in units_) + ". "
              f"Overlaps between parts of two different drawers: {len(between)}. Overlaps that grow on the way:", "",
              "| Parts | Drawers | Largest (mm² of section) |", "|---|---|---|"]
        for (a, b), rs in sorted(kinds.items(), key=lambda kv: -len(kv[1])):
            L.append(f"| {a} / {b} | {len(rs)} | {max(r['max'] for r in rs):.2f} |")
        L += ["", "The key's cam grazing the module's front notch as it turns is the same as in a single drawer (README \"Motion\");",
              "it only happens on the bottom and top drawers, the ones whose key finds the frame's notches."]
    L.append("")
L += ["", "## Units", ""]
for key, status, pl, unplaced, explained, ck, notes in rows:
    head = f"- `{key}` **{status}**"
    if pl:
        head += f", {len(pl['parts'])} parts placed"
    if ck.get("render"):
        head += f", check: `{ck['render']}`"
    L.append(head)
    for n in ([ck["note"]] if ck.get("note") else []) + notes:
        L.append(f"  - {n}")
    for lab, path, _ in unplaced:
        L.append(f"  - not placed: {lab} (`{path.split('/')[-1]}`)")
open(out, "w", encoding="utf-8").write("\n".join(L) + "\n")
print(out, dict(tot))
